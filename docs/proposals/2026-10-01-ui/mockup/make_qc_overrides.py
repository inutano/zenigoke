#!/usr/bin/env python3
"""Turn the 2026-10-01 QC investigation TSVs into meta/qc_overrides.tsv.

The QC flags here replace the provisional rule-based flags in make_index.py.
For ChIP/ATAC the true alignment rate and the estimated duplication rate also
replace the DB values, which are mislabelled (see docs/qc/).
Run make_index.py afterwards.
"""
from __future__ import annotations

import csv
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
QC = HERE.parents[2] / "qc"
CHIP_TSV = QC / "2026-10-01-chip-atlas-qc.tsv"
BS_TSV = QC / "2026-10-01-bsseq-qc.tsv"
OUT = HERE / "meta" / "qc_overrides.tsv"


def split_top_level(s: str) -> list[str]:
    """Split on ';' outside parentheses."""
    parts, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth = max(0, depth - 1)
        if ch == ";" and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return [p.strip() for p in parts if p.strip() and p.strip() != "none"]


def clean(reason: str) -> str:
    # The overrides file uses ';' as its own separator.
    return reason.replace(";", ",").replace("_", " ")


def main() -> None:
    rows = []
    for r in csv.DictReader(CHIP_TSV.open(), delimiter="\t"):
        reasons = [clean(x) for x in split_top_level(r["cause"])]
        if r.get("peak_flag") == "WARN":
            reasons.append(f"{r['peaks_in_organelle_like_pct']}% of peaks in organelle-like (NUPT/NUMT) regions")
        rows.append([r["accession"], r["qc_flag"], ";".join(reasons), r["aligned_pct"], r["dup_pct"]])
    for r in csv.DictReader(BS_TSV.open(), delimiter="\t"):
        reasons = [clean(x) for x in split_top_level(r["cause"])]
        rows.append([r["accession"], r["qc_flag"], ";".join(reasons), "", ""])

    with OUT.open("w", newline="") as fh:
        fh.write("# Generated by make_qc_overrides.py from docs/qc/2026-10-01-*-qc.tsv.\n")
        fh.write("# Rows here replace the provisional rule-based flag. reasons: semicolon-separated.\n")
        fh.write("# aligned_pct / dup_pct (ChIP/ATAC only) replace the mislabelled DB mapping/duplication rates.\n")
        w = csv.writer(fh, delimiter="\t", lineterminator="\n")
        w.writerow(["accession", "qc_flag", "reasons", "aligned_pct", "dup_pct"])
        w.writerows(rows)
    print(f"wrote {len(rows)} rows to {OUT}")


if __name__ == "__main__":
    main()
